/// Data Transfer Object (DTO) for AI Usage Events.
///
/// Encapsulates serialization, deserialization, and schema normalization
/// between raw Firestore maps and the clean domain [UsageEventModel].
///
/// Design Highlights:
/// 1. Sparse Storage: Does not write `imageCount: 0` or `pdfCount: 0` for
///    text generation, preventing document bloat.
/// 2. Primary Key Optimization: Does not duplicate the document ID as an
///    internal field inside the document payload (`id` is already `doc.id`).
/// 3. Request Correlation: Preserves `requestId` to connect usage telemetry
///    with chat messages and analytics audit traces.
class UsageEventDto {
  /// Unique document ID in Firestore: corresponds directly to [requestId] (UUID v4).
  /// Used as the document key in the `usageEvents` subcollection for idempotency.
  final String eventId;

  /// String identifier of the AI provider that executed the request (e.g. 'gemini', 'openai').
  final String providerId;

  /// Concrete AI model string invoked (e.g. 'gemini-3.8-flash', 'gpt-4o').
  final String model;

  /// Modality capability requested (e.g. 'text_generation', 'image_generation').
  final String capability;

  /// Trace correlation UUID linking prompt submission, analytics, and this usage record.
  final String requestId;

  /// Optional conversation ID if this event occurred inside a persistent chat thread.
  final String? conversationId;

  /// Optional message turn ID linked to this event.
  final String? messageId;

  /// Number of prompt/input tokens consumed by the provider.
  final int inputTokens;

  /// Number of completion/output tokens generated by the provider.
  final int outputTokens;

  /// Sum of input and output tokens (`inputTokens + outputTokens`).
  final int totalTokens;

  /// Number of generated images (0 if non-image request; omitted in Firestore when 0).
  final int imageCount;

  /// Number of parsed PDF documents (0 if non-PDF request; omitted in Firestore when 0).
  final int pdfCount;

  /// Computed cost in USD based on provider pricing tables and token metrics.
  final double estimatedCostUsd;

  /// Client timestamp when the usage event was constructed.
  final DateTime createdAt;

  /// Partitioning month key in 'YYYY-MM' format (e.g. '2026-10') for monthly aggregations.
  final String monthKey;

  /// Last 6 characters of the API key that produced this event.
  ///
  /// Non-secret fingerprint used by [UsageFirestoreDao] to detect key rotation:
  /// if this hint differs from the [summaryFieldKeyHint] stored in Firestore,
  /// the summary counters are reset so the new key starts with zero budget usage.
  /// NOT persisted inside the event document payload itself.
  final String? keyHint;

  const UsageEventDto({
    required this.eventId,
    required this.providerId,
    required this.model,
    required this.capability,
    required this.requestId,
    this.conversationId,
    this.messageId,
    this.inputTokens = 0,
    this.outputTokens = 0,
    this.totalTokens = 0,
    this.imageCount = 0,
    this.pdfCount = 0,
    this.estimatedCostUsd = 0.0,
    required this.createdAt,
    required this.monthKey,
    this.keyHint,
  });

  /// Converts domain [UsageEventModel] into a [UsageEventDto] for persistence.
  factory UsageEventDto.fromDomain(UsageEventModel model) {
    return UsageEventDto(
      eventId: model.id,
      providerId: model.provider.id,
      model: model.model,
      capability: model.capability.id,
      requestId: model.requestId,
      conversationId: model.conversationId,
      messageId: model.messageId,
      inputTokens: model.inputTokens,
      outputTokens: model.outputTokens,
      totalTokens: model.totalTokens,
      imageCount: model.imageCount,
      pdfCount: model.pdfCount,
      estimatedCostUsd: model.estimatedCostUsd,
      createdAt: model.createdAt,
      monthKey: model.monthKey,
      keyHint: model.keyHint,
    );
  }

  /// Converts this DTO back into the pure domain entity [UsageEventModel].
  UsageEventModel toDomain() {
    return UsageEventModel(
      id: eventId,
      provider: AiProviderId.fromId(providerId),
      model: model,
      capability: AiCapability.fromId(capability),
      requestId: requestId,
      conversationId: conversationId,
      messageId: messageId,
      inputTokens: inputTokens,
      outputTokens: outputTokens,
      totalTokens: totalTokens,
      imageCount: imageCount,
      pdfCount: pdfCount,
      estimatedCostUsd: estimatedCostUsd,
      createdAt: createdAt,
      monthKey: monthKey,
    );
  }

  /// Deserializes a Firestore document snapshot defensively.
  ///
  /// Extracts the primary key from [docId], while falling back to legacy internal
  /// fields if reading historical data.
  factory UsageEventDto.fromFirestore(
    String docId,
    Map<String, dynamic> data,
  ) {
    // 1. Resolve primary key: use docId, fallback to legacy internal 'id' field if present
    final resolvedEventId = docId.isNotEmpty
        ? docId
        : (data[FirebaseCollections.usageFieldId] as String? ?? '');

    // 2. Resolve request correlation ID: fallback to eventId if absent
    final resolvedRequestId =
        data[FirebaseCollections.usageFieldRequestId] as String? ??
            resolvedEventId;

    // 3. Resolve createdAt timestamp: supports Firestore Timestamp or client DateTime
    final rawCreatedAt = data[FirebaseCollections.usageFieldCreatedAt];
    final DateTime resolvedCreatedAt;
    if (rawCreatedAt is Timestamp) {
      resolvedCreatedAt = rawCreatedAt.toDate();
    } else if (rawCreatedAt is String) {
      resolvedCreatedAt = DateTime.tryParse(rawCreatedAt) ?? DateTime.now();
    } else {
      resolvedCreatedAt = DateTime.now();
    }

    // 4. Token metrics with defensive type conversion
    final inputTokens =
        (data[FirebaseCollections.usageFieldInputTokens] as num?)?.toInt() ?? 0;
    final outputTokens =
        (data[FirebaseCollections.usageFieldOutputTokens] as num?)?.toInt() ?? 0;
    final totalTokens =
        (data[FirebaseCollections.usageFieldTotalTokens] as num?)?.toInt() ??
            (inputTokens + outputTokens);

    // 5. Sparse attachment counts: defaults to 0 if omitted from document payload
    final imageCount =
        (data[FirebaseCollections.usageFieldImageCount] as num?)?.toInt() ?? 0;
    final pdfCount =
        (data[FirebaseCollections.usageFieldPdfCount] as num?)?.toInt() ?? 0;

    return UsageEventDto(
      eventId: resolvedEventId,
      providerId:
          data[FirebaseCollections.usageFieldProvider] as String? ?? '',
      model: data[FirebaseCollections.usageFieldModel] as String? ?? '',
      capability:
          data[FirebaseCollections.usageFieldCapability] as String? ??
              AiCapability.textGeneration.id,
      requestId: resolvedRequestId,
      conversationId:
          data[FirebaseCollections.usageFieldConversationId] as String?,
      messageId: data[FirebaseCollections.usageFieldMessageId] as String?,
      inputTokens: inputTokens,
      outputTokens: outputTokens,
      totalTokens: totalTokens,
      imageCount: imageCount,
      pdfCount: pdfCount,
      estimatedCostUsd:
          (data[FirebaseCollections.usageFieldEstimatedCostUsd] as num?)
                  ?.toDouble() ??
              0.0,
      createdAt: resolvedCreatedAt,
      monthKey: data[FirebaseCollections.usageFieldMonthKey] as String? ??
          UsageEventModel.monthKeyFrom(resolvedCreatedAt),
    );
  }

  /// Serializes DTO into a normalized Firestore map.
  ///
  /// Omission Rules:
  /// - Does NOT write internal `id` key (Firestore `doc.id` holds the primary key).
  /// - Only writes `imageCount` if `imageCount > 0`.
  /// - Only writes `pdfCount` if `pdfCount > 0`.
  /// - Always writes `requestId` for correlation and auditing.
  Map<String, dynamic> toFirestoreMap() {
    return {
      FirebaseCollections.usageFieldProvider: providerId,
      FirebaseCollections.usageFieldModel: model,
      FirebaseCollections.usageFieldCapability: capability,
      FirebaseCollections.usageFieldRequestId: requestId,
      if (conversationId != null)
        FirebaseCollections.usageFieldConversationId: conversationId,
      if (messageId != null)
        FirebaseCollections.usageFieldMessageId: messageId,
      FirebaseCollections.usageFieldInputTokens: inputTokens,
      FirebaseCollections.usageFieldOutputTokens: outputTokens,
      FirebaseCollections.usageFieldTotalTokens: totalTokens,
      // Sparse Attachment Counts: omit 0 values to conserve bytes on pure text chats
      if (imageCount > 0) FirebaseCollections.usageFieldImageCount: imageCount,
      if (pdfCount > 0) FirebaseCollections.usageFieldPdfCount: pdfCount,
      FirebaseCollections.usageFieldEstimatedCostUsd: estimatedCostUsd,
      FirebaseCollections.usageFieldCreatedAt: FieldValue.serverTimestamp(),
      FirebaseCollections.usageFieldMonthKey: monthKey,
    };
  }
}

/// Data Transfer Object (DTO) for AI Usage Summaries & Budget Profiles.
///
/// Encapsulates serialization and defensive parsing for provider-level aggregate
/// documents stored at `AI_Voice_Genie/Users/User_Model/{uid}/usageSummaries/{providerId}`.
class UsageSummaryDto {
  /// AI Provider string ID (e.g. 'gemini', 'openai', 'claude').
  final String providerId;

  /// Explicit Firestore document ID (e.g. 'gemini_f7cK2A').
  final String? docId;

  /// Monthly budget limit configured by user in USD (null if disabled/unset).
  final double? monthlyBudgetUsd;

  /// Historical external spend recorded outside the app in USD (null if 0.0).
  final double? alreadyUsedUsd;

  /// Map of month keys ('YYYY-MM') to structured monthly activity metrics.
  final Map<String, MonthlyUsageData> monthlyData;

  /// All-time cumulative token count across all months for this provider.
  final int? lifetimeTotalTokens;

  /// Last server update timestamp.
  final DateTime? updatedAt;

  /// Legacy budget enablement flag from historical records.
  final bool? legacyEnabled;

  /// Last 6 characters of the API key that last incremented this summary document.
  /// Used to detect key rotation and reset budget counters when a new key is detected.
  final String? keyHint;

  /// AES-256 encrypted API key ciphertext stored at rest in Firestore.
  final String? encryptedApiKey;

  const UsageSummaryDto({
    required this.providerId,
    this.docId,
    this.monthlyBudgetUsd,
    this.alreadyUsedUsd,
    this.monthlyData = const {},
    this.lifetimeTotalTokens,
    this.updatedAt,
    this.legacyEnabled,
    this.keyHint,
    this.encryptedApiKey,
  });

  /// Converts domain [UsageSummaryModel] into DTO representation.
  factory UsageSummaryDto.fromDomain(UsageSummaryModel model) {
    return UsageSummaryDto(
      providerId: model.provider.id,
      docId: model.docId,
      monthlyBudgetUsd: model.totalBudgetUsd,
      alreadyUsedUsd: model.alreadyUsedUsd,
      monthlyData: model.monthlyData,
      lifetimeTotalTokens: model.lifetimeTokens(),
      updatedAt: model.updatedAt,
      legacyEnabled: model.enabled,
      keyHint: model.keyHint,
      encryptedApiKey: model.encryptedApiKey,
    );
  }

  /// Converts this DTO back into the domain [UsageSummaryModel].
  UsageSummaryModel toDomain() {
    final provider = AiProviderId.fromId(providerId);

    return UsageSummaryModel(
      provider: provider,
      docId: docId,
      totalBudgetUsd: monthlyBudgetUsd,
      alreadyUsedUsd: alreadyUsedUsd,
      monthlyData: monthlyData,
      updatedAt: updatedAt,
      keyHint: keyHint,
      encryptedApiKey: encryptedApiKey,
      lifetimeTotalTokens: lifetimeTotalTokens,
    );
  }

  /// Deserializes a Firestore document snapshot defensively.
  factory UsageSummaryDto.fromFirestore(
    String docId,
    Map<String, dynamic> data,
  ) {
    // 1. Resolve Provider ID: prefer docId prefix (e.g. 'gemini_f7cK2A' -> 'gemini'), fallback to data['provider']
    final resolvedProviderId = docId.contains('_')
        ? docId.split('_').first
        : (data[FirebaseCollections.usageFieldProvider] as String? ?? (docId.isNotEmpty ? docId : ''));

    // 2. Parse nested monthlyData map defensively
    final rawMonthly = data['monthlyData'] as Map<dynamic, dynamic>? ?? {};
    final parsedMonthly = <String, MonthlyUsageData>{};
    rawMonthly.forEach((key, value) {
      if (key is String && value is Map) {
        parsedMonthly[key] =
            MonthlyUsageData.fromMap(Map<String, dynamic>.from(value));
      }
    });

    // 3. Resolve Lifetime Tokens: prefer 'lifetimeTotalTokens', fallback to legacy 'totalTokens'
    final rawLifetimeTokens =
        (data[FirebaseCollections.usageFieldLifetimeTotalTokens] as num?)
                ?.toInt() ??
            (data[FirebaseCollections.usageFieldTotalTokens] as num?)?.toInt();

    // 4. Resolve Timestamp
    final rawUpdatedAt = data[FirebaseCollections.usageFieldUpdatedAt];
    DateTime? resolvedUpdatedAt;
    if (rawUpdatedAt is Timestamp) {
      resolvedUpdatedAt = rawUpdatedAt.toDate();
    } else if (rawUpdatedAt is String) {
      resolvedUpdatedAt = DateTime.tryParse(rawUpdatedAt);
    }

    // 5. Resolve keyHint — last 6 chars of the API key fingerprint
    var resolvedKeyHint =
        data[FirebaseCollections.summaryFieldKeyHint] as String?;
    if (resolvedKeyHint == null && docId.contains('_')) {
      final parts = docId.split('_');
      if (parts.length >= 2 && parts.last.isNotEmpty) {
        resolvedKeyHint = parts.last;
      }
    }

    // 6. Resolve encryptedApiKey
    final resolvedEncryptedApiKey = data[FirebaseCollections.fieldApiKey] as String? ??
        data['encryptedApiKey'] as String?;

    return UsageSummaryDto(
      providerId: resolvedProviderId,
      docId: docId,
      monthlyBudgetUsd:
          (data[FirebaseCollections.budgetFieldMonthlyBudgetUsd] as num?)
              ?.toDouble(),
      alreadyUsedUsd:
          (data[FirebaseCollections.budgetFieldAlreadyUsedUsd] as num?)
              ?.toDouble(),
      monthlyData: parsedMonthly,
      lifetimeTotalTokens: rawLifetimeTokens,
      updatedAt: resolvedUpdatedAt,
      keyHint: resolvedKeyHint,
      encryptedApiKey: resolvedEncryptedApiKey,
    );
  }

  /// Serializes budget settings map for Firestore updates.
  Map<String, dynamic> toBudgetUpdateMap() {
    return {
      FirebaseCollections.budgetFieldMonthlyBudgetUsd: monthlyBudgetUsd,
      FirebaseCollections.budgetFieldAlreadyUsedUsd: alreadyUsedUsd,
      if (keyHint != null) FirebaseCollections.summaryFieldKeyHint: keyHint,
      if (encryptedApiKey != null)
        FirebaseCollections.fieldApiKey: encryptedApiKey,
      FirebaseCollections.usageFieldUpdatedAt: FieldValue.serverTimestamp(),
    };
  }

  /// Serializes a key-rotation reset document for Firestore.
  Map<String, dynamic> toKeyRotationResetMap({
    required String newKeyHint,
    String? newEncryptedApiKey,
  }) {
    return {
      'monthlyData': {},
      FirebaseCollections.usageFieldLifetimeTotalTokens: 0,
      FirebaseCollections.summaryFieldKeyHint: newKeyHint,
      if (newEncryptedApiKey != null)
        FirebaseCollections.fieldApiKey: newEncryptedApiKey,
      FirebaseCollections.usageFieldUpdatedAt: FieldValue.serverTimestamp(),
    };
  }
}
