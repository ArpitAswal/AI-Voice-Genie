import '../../../core/enums/app_enums.dart';
import '../data/usage_dto.dart';

/// Domain Entity representing a single AI execution's telemetry event.
///
/// Records prompt and completion tokens, generated media count, parsed document count,
/// and estimated costs in USD. Persisted in Firestore under:
/// `AI_Voice_Genie/Users/User_Model/{uid}/usageEvents/{eventId}`.
class UsageEventModel {
  /// Unique event record identifier: corresponds directly to [requestId] (correlation UUID).
  /// Used as the document key in Firestore for write idempotency and 1:1 message correlation.
  final String id;

  /// The AI provider that executed the request (e.g. Gemini, OpenAI, Claude).
  /// Determines which pricing table and summary document is updated.
  final AiProviderId provider;

  /// The concrete model version invoked (e.g. "gemini-3.8-flash", "gpt-4o").
  /// Enables fine-grained cost estimation per model tier.
  final String model;

  /// Modality requested (e.g. text generation, image generation, speech, PDF parsing).
  /// Used to differentiate token-based vs image/page-based pricing models.
  final AiCapability capability;

  /// Correlation UUID originating from [AiRequest.requestId].
  /// Links this telemetry record with the user prompt, AI message turn, and analytics events.
  final String requestId;

  /// Optional ID of the parent conversation thread, if the request occurred in chat.
  final String? conversationId;

  /// Optional ID of the specific message turn linked to this event.
  final String? messageId;

  /// Number of prompt/input tokens processed by the LLM.
  final int inputTokens;

  /// Number of completion/output tokens generated by the LLM.
  final int outputTokens;

  /// Total tokens consumed for this interaction (`inputTokens + outputTokens`).
  final int totalTokens;

  /// Number of images generated (0 for pure text chats).
  /// Omitted in Firestore when 0 to prevent document bloat.
  final int imageCount;

  /// Number of PDF documents parsed (0 for pure text chats).
  /// Omitted in Firestore when 0 to prevent document bloat.
  final int pdfCount;

  /// Estimated financial cost in USD calculated from the provider pricing table.
  final double estimatedCostUsd;

  /// Timestamp when the usage metrics were captured on the client upon response completion.
  final DateTime createdAt;

  /// Partition key in "YYYY-MM" format (e.g. "2026-10") used for monthly grouping.
  final String monthKey;

  /// Last 6 characters of the API key that produced this event.
  ///
  /// Non-secret: used only as a rotation fingerprint by [UsageFirestoreDao] to
  /// detect when the user replaced their API key and reset budget counters.
  /// Never written to the usageEvents document payload.
  final String? keyHint;

  const UsageEventModel({
    required this.id,
    required this.provider,
    required this.model,
    required this.capability,
    required this.requestId,
    this.conversationId,
    this.messageId,
    this.inputTokens = 0,
    this.outputTokens = 0,
    this.totalTokens = 0,
    this.imageCount = 0,
    this.pdfCount = 0,
    this.estimatedCostUsd = 0.0,
    required this.createdAt,
    required this.monthKey,
    this.keyHint,
  });

  /// Bridges Firestore serialization through [UsageEventDto] to enforce sparse fields
  /// and omit redundant internal IDs.
  Map<String, dynamic> toFirestore() =>
      UsageEventDto.fromDomain(this).toFirestoreMap();

  /// Bridges Firestore deserialization through [UsageEventDto] for defensive parsing.
  factory UsageEventModel.fromFirestore(
    String docId,
    Map<String, dynamic> data,
  ) =>
      UsageEventDto.fromFirestore(docId, data).toDomain();

  /// Generates the month key string from a [DateTime], e.g. "2026-10".
  static String monthKeyFrom(DateTime dt) {
    final month = dt.month.toString().padLeft(2, '0');
    return '${dt.year}-$month';
  }

  /// Returns the current month key for the device's local clock.
  static String get currentMonthKey => monthKeyFrom(DateTime.now());

  @override
  String toString() => 'UsageEventModel('
      'id: $id, provider: ${provider.id}, model: $model, '
      'tokens: $totalTokens, cost: \$${estimatedCostUsd.toStringAsFixed(4)}, '
      'month: $monthKey)';
}
